def main():
    BOM_FILE.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "part_number",
        "description",
        "value",
        "footprint",
        "quantity",
        "references",
        "lcsc_part",
    ]
    with open(BOM_FILE, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in BOM_DATA:
            writer.writerow(row)
    print(f"Wrote {len(BOM_DATA)} BOM rows to {BOM_FILE}")


if __name__ == "__main__":
    main()
